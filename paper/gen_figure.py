# -*- coding: utf-8 -*-
"""Programmatically draw the audit-framework schematic (Fig. 1).

Pure Pillow drawing, deterministic, no generative image model.  The figure is
re-generated by running this file; the PNG in the paper is its output.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parent
BG = (255, 255, 255)
INK = (24, 24, 24)
FILL = (240, 241, 243)
FILL_ACCENT = (228, 232, 238)
EDGE = (60, 62, 66)

W, H = 1280, 470
BW, BH = 560, 116
X = [40, 660]
Y = [34, 178, 322]

FONT_CANDIDATES = [
    r"C:\Windows\Fonts\arialbd.ttf",
    r"C:\Windows\Fonts\segoeuib.ttf",
    r"C:\Windows\Fonts\calibrib.ttf",
]
FONT_BODY = [
    r"C:\Windows\Fonts\arial.ttf",
    r"C:\Windows\Fonts\segoeui.ttf",
    r"C:\Windows\Fonts\calibri.ttf",
]


def load(paths, size):
    for p in paths:
        if Path(p).exists():
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


title_font = load(FONT_CANDIDATES, 25)
body_font = load(FONT_BODY, 21)

BOXES = {
    1: ("1  Base model and quantizers", ["Llama-3-8B base weights  W_l",
                                          "NF4  .  INT4-RTN  .  INT8"], X[0], Y[0], False),
    2: ("2  Per-layer diagnostics", ["eps_l = ||E_l||_F / ||W_l||_F",
                                      "CV, min/max ratio, Spearman rho"], X[1], Y[0], False),
    3: ("3  Allocation score", ["s_l = eps_l * ||W_l||_F",
                                "identity:  s_l  ==  ||E_l||_F"], X[1], Y[1], True),
    4: ("4  Degeneracy test", ["rho(s_l, ||W_l||_F) = 1 over layers?",
                               "if yes: error-aware = norm-aware"], X[0], Y[1], True),
    5: ("5  Controlled adapter training", ["QLoRA . AdaQ . AdaLoRA . DoRA",
                                           "identical budget, LR, steps, data"], X[0], Y[2], False),
    6: ("6  Evaluation and inference", ["MMLU (5-shot) . GSM8K (4-shot)",
                                        "paired t, BH-FDR, MDE, TOST"], X[1], Y[2], False),
}

# serpentine order: 1 -> 2 -> 3 -> 4 -> 5 -> 6
ORDER = [1, 2, 3, 4, 5, 6]


def render():
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)

    for i in ORDER:
        title, lines, x, y, accent = BOXES[i]
        fill = FILL_ACCENT if accent else FILL
        d.rounded_rectangle([x, y, x + BW, y + BH], radius=10, fill=fill,
                            outline=EDGE, width=2)
        d.text((x + 18, y + 12), title, font=title_font, fill=INK)
        ty = y + 52
        for ln in lines:
            d.text((x + 18, ty), ln, font=body_font, fill=INK)
            ty += 30

    def arrow(p0, p1):
        d.line([p0, p1], fill=EDGE, width=3)
        ax, ay = p1
        px, py = p0
        if abs(ax - px) > abs(ay - py):
            s = 1 if ax > px else -1
            d.polygon([(ax, ay), (ax - 12 * s, ay - 7), (ax - 12 * s, ay + 7)], fill=EDGE)
        else:
            s = 1 if ay > py else -1
            d.polygon([(ax, ay), (ax - 7, ay - 12 * s), (ax + 7, ay - 12 * s)], fill=EDGE)

    # 1 -> 2 (right)
    arrow((X[0] + BW, Y[0] + BH // 2), (X[1] - 4, Y[0] + BH // 2))
    # 2 -> 3 (down)
    arrow((X[1] + BW // 2, Y[0] + BH), (X[1] + BW // 2, Y[1] - 4))
    # 3 -> 4 (left)
    arrow((X[1], Y[1] + BH // 2), (X[0] + BW + 4, Y[1] + BH // 2))
    # 4 -> 5 (down)
    arrow((X[0] + BW // 2, Y[1] + BH), (X[0] + BW // 2, Y[2] - 4))
    # 5 -> 6 (right)
    arrow((X[0] + BW, Y[2] + BH // 2), (X[1] - 4, Y[2] + BH // 2))

    img.save(OUT / "audit_framework.png", dpi=(300, 300))
    return OUT / "audit_framework.png"


if __name__ == "__main__":
    print(render())
